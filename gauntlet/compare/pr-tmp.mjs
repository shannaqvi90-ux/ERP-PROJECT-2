import { chromium } from 'playwright-core';
import { findChromium } from './lib/browser.mjs';
const b = await chromium.launch({ executablePath: findChromium() });
const page = await (await b.newContext({ viewport: { width: 1600, height: 900 } })).newPage();
await page.goto('http://localhost:21800/');
await page.locator('input[name="email"]:focus').waitFor();
await page.keyboard.type('admin@alnoor.example'); await page.keyboard.press('Tab'); await page.keyboard.type('Demo-Pass-2026'); await page.keyboard.press('Enter');
await page.locator('nav[aria-label="Main navigation"]').waitFor();
await page.getByRole('navigation').getByRole('link', { name: 'Contacts', exact: true }).first().click();
await page.waitForTimeout(3000);
console.log(await page.locator('table[role=grid]').getAttribute('aria-rowcount'), await page.locator('button.ct-tag').allTextContents());
await page.screenshot({ path: '/tmp/claude-1000/c.png' });
await b.close();

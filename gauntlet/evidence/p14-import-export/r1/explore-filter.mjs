// Critic exploration (not a measurement): the Tags column filter path on the contacts list.
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(path.join(process.cwd(), 'package.json'));
const { chromium } = require('playwright-core');
const { findChromium } = await import(path.join(process.cwd(), 'lib/browser.mjs'));
const BASE = 'http://localhost:21450';
const b = await chromium.launch({ executablePath: findChromium() });
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto(BASE + '/'); await page.locator('input[name="email"]:focus').waitFor();
await page.keyboard.type('admin@alnoor.example'); await page.keyboard.press('Tab'); await page.keyboard.type('Demo-Pass-2026'); await page.keyboard.press('Enter');
await page.locator('nav[aria-label="Main navigation"]').waitFor();
console.log('after sign-in url', page.url(), 'focus', await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 100)));
await page.getByRole('navigation').getByRole('link', { name: 'Contacts', exact: true }).first().click();
await page.locator('table[role=grid]').waitFor();
await page.waitForTimeout(1000);
const menu = page.getByRole('button', { name: /Tags/ });
console.log('tags buttons', await menu.count(), await menu.evaluateAll(es => es.map(e => e.getAttribute('aria-label') + '|' + e.textContent)));
await page.getByRole('button', { name: 'Options for the column Tags' }).click().catch(async e => { console.log('no exact', e.message.slice(0, 100)); });
await page.waitForTimeout(500);
console.log('menu items', await page.getByRole('menuitem').allTextContents());
await page.getByRole('menuitem', { name: /Filter/ }).first().click();
await page.waitForTimeout(500);
console.log('focus in filter', await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 200)));
await page.keyboard.press('Tab'); console.log('focus2', await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 160))); await page.keyboard.type('Government');
await page.keyboard.press('Enter');
await page.waitForTimeout(2500);
console.log('rowcount', await page.locator('table[role=grid]').getAttribute('aria-rowcount'), 'url', page.url());
await page.screenshot({ path: '/home/shan/evidence-staging/p14-import-export/r1/explore-filter.jpg', type: 'jpeg', quality: 50 });
await page.getByRole('button', { name: 'Print or export' }).click();
console.log('print items', await page.getByRole('menuitem').allTextContents());
await b.close();

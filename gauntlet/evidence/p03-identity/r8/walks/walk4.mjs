// Viewer: enabled role checkboxes on a read-only record. Admin: effective permissions panel.
import { launch, signIn, shot, dump, BASE } from "./pw.mjs";
const b = await launch(); const ctx = await b.newContext({ viewport: { width: 1600, height: 900 } });
const page = await ctx.newPage(); const reqs = [];
page.on("request", (r) => r.method() !== "GET" && r.url().includes("/api/") && reqs.push(`${r.method()} ${r.url()}`));
await signIn(page, "viewer@alnoor.example");
await page.goto(BASE + "/identity/users?q=accountant@alnoor.example"); await page.waitForTimeout(1500);
await page.keyboard.press("Enter"); await page.waitForTimeout(1200);
const clerk = page.locator("label", { hasText: "Clerk (restricted)" }).locator("input[type=checkbox]");
console.log("clerk enabled:", await clerk.isEnabled());
await clerk.check({ force: true }).catch((e) => console.log("check failed", e.message.split("\n")[0]));
await page.waitForTimeout(300);
console.log("clerk checked now:", await clerk.isChecked());
await dump(page, "viewer after ticking");
await page.keyboard.press("Control+s"); await page.waitForTimeout(800);
await page.keyboard.press("Control+Enter"); await page.waitForTimeout(800);
console.log("non-GET requests from viewer:", reqs);
await shot(page, "07-viewer-ticks-role-on-read-only-record-en");
await page.keyboard.press("Escape"); await page.waitForTimeout(800);
await dump(page, "after Escape");
await page.close(); await ctx.clearCookies();
const p = await ctx.newPage();
await p.setViewportSize({ width: 1920, height: 1080 });
await signIn(p, "admin@alnoor.example");
const mgr = await p.evaluate(async () => (await (await fetch("/api/identity/users?take=5&search=" + encodeURIComponent("manager"))).json()).items.map((u) => u.email));
console.log("manager search", mgr);
const users = await p.evaluate(async () => (await (await fetch("/api/identity/users?take=10")).json()).items.map((u) => [u.email, u.roles ?? u.roleNames]));
console.log(JSON.stringify(users));
await b.close();

import { open, signIn, focused, EV, BASE } from './h.mjs';
import fs from 'node:fs';
const log = []; const L = (s) => { log.push(s); console.log(s); };
const { browser, page, errors } = await open({ width: 1600 });
await signIn(page, 'admin.ar@alnoor.example');
await page.keyboard.press('g'); await page.keyboard.press('u'); await page.waitForTimeout(2500);
L('dir ' + await page.evaluate(() => document.documentElement.dir) + ' head ' + (await page.locator('main').innerText()).slice(0, 160).replace(/\n/g, ' | '));
const hdrs = await page.locator('main [role=columnheader]').evaluateAll((h) => h.map((x) => ({ t: x.innerText.trim().split('\n')[0], cut: x.scrollWidth > x.clientWidth + 1 })));
L('headers: ' + JSON.stringify(hdrs));
await page.keyboard.press('Alt+n'); await page.waitForTimeout(800);
L('Alt+N focus: ' + await focused(page));
const stamp = Date.now().toString(36).slice(-5);
await page.keyboard.type(`amin.${stamp}@alnoor.example`);
await page.keyboard.press('Alt+o'); await page.waitForTimeout(300);
L('Alt+O focus: ' + await focused(page));
await page.keyboard.type('قراءة'); await page.keyboard.press('Enter'); await page.waitForTimeout(300);
L('ticked: ' + JSON.stringify(await page.locator('aside .id-roles input[type=checkbox]:checked').evaluateAll((els) => els.map((e) => e.closest('label')?.innerText.replace(/\n/g, ' ')))));
await page.screenshot({ path: `${EV}/02-new-user-keyboard-role-finder-ar.jpg`, quality: 70, type: 'jpeg' });
await page.keyboard.press('Control+Enter'); await page.waitForTimeout(1500);
L('after save: ' + (await page.locator('aside').first().innerText()).slice(0, 260).replace(/\n/g, ' | '));
await page.keyboard.press('?'); await page.waitForTimeout(500);
const sheet = await page.locator('[role=dialog]').first().innerText().catch(() => '');
L('shortcut sheet lists Alt+O: ' + /Alt\s*\+?\s*O/i.test(sheet) + ' | ' + sheet.split('\n').filter((l) => /O\b|دور/.test(l)).slice(0, 4).join(' / '));
L('errors: ' + JSON.stringify(errors));
fs.writeFileSync(`${EV}/walks/w9-arabic-keyboard.txt`, log.join('\n'));
await browser.close();

import { open, signIn, focused, EV, BASE } from './h.mjs';
import fs from 'node:fs';
const log = []; const L = (s) => { log.push(s); console.log(s); };
const [email, code] = process.argv.slice(2);
const { browser, page, errors } = await open();
await signIn(page, email, code);
L('after code sign-in: ' + (await page.locator('body').innerText()).slice(0, 400).replace(/\n/g, ' | '));
L('focus: ' + await focused(page));
const pw = 'Clerk-Pass-2026!x';
const pws = page.locator('input[type=password]');
L('password fields: ' + await pws.count());
for (let i = 1; i < await pws.count(); i++) await pws.nth(i).fill(pw);
await page.keyboard.press('Enter'); await page.waitForTimeout(2000);
L('after choose: url ' + page.url() + ' text ' + (await page.locator('body').innerText()).slice(0, 300).replace(/\n/g, ' | '));
await page.goto(BASE + '/identity/users'); await page.waitForTimeout(2500);
const main = await page.locator('main').innerText();
L('users list as read-only: has "New user": ' + main.includes('New user') + ' | head ' + main.slice(0, 200).replace(/\n/g, ' | '));
await page.keyboard.press('Alt+n'); await page.waitForTimeout(500);
L('Alt+N opened a form: ' + (await page.locator('aside input[name=email]').count()));
await page.keyboard.press('Control+k'); await page.waitForTimeout(400); await page.keyboard.type('new'); await page.waitForTimeout(500);
L('palette for "new": ' + (await page.locator('[role=dialog], [role=listbox]').first().innerText().catch(() => 'none')).slice(0, 300).replace(/\n/g, ' | '));
await page.keyboard.press('Escape');
await page.locator('main [role=row]').nth(2).click(); await page.waitForTimeout(1200);
const aside = await page.locator('aside').first().innerText();
L('opened record buttons: ' + JSON.stringify(await page.locator('aside button:visible').evaluateAll((b) => b.map((x) => x.innerText.trim()).filter(Boolean))));
L('editable inputs in record: ' + await page.locator('aside input:not([disabled]):not([type=search])').evaluateAll((els) => els.filter((e) => !e.closest('fieldset[disabled]') && !e.readOnly).length));
await page.screenshot({ path: EV + '/05-read-only-user-record-no-actions-en.jpg', quality: 70, type: 'jpeg' });
// API with the same session cookie
const api = async (m, p, b) => page.evaluate(async ([m, p, b]) => { const r = await fetch(p, { method: m, headers: { 'content-type': 'application/json', 'X-Erp-Request': '1' }, body: b ? JSON.stringify(b) : undefined }); return r.status; }, [m, p, b]);
L('API POST users: ' + await api('POST', '/api/identity/users', { email: 'z' + Date.now() + '@alnoor.example', displayName: 'z', language: 'en', roleIds: [] }));
L('API POST roles: ' + await api('POST', '/api/identity/roles', { nameEn: 'z', nameAr: 'ز', permissions: [] }));
L('API GET users: ' + await api('GET', '/api/identity/users?take=1'));
L('API GET roles: ' + await api('GET', '/api/identity/roles?take=1'));
L('API GET companies (tenancy): ' + await api('GET', '/api/tenancy/companies'));
L('API PUT tenant: ' + await api('PUT', '/api/tenancy/tenant', {}));
L('errors: ' + JSON.stringify(errors));
fs.writeFileSync(EV + '/walks/w2.txt', log.join('\n'));
await browser.close();

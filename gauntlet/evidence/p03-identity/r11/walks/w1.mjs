import { open, signIn, focused, EV } from './h.mjs';
const log = []; const L = (s) => { log.push(s); console.log(s); };
const { browser, page, errors } = await open();
await signIn(page, 'admin@alnoor.example');
L('after sign in url ' + page.url());
await page.keyboard.press('g'); await page.keyboard.press('u');
await page.waitForTimeout(2000);
L('users url ' + page.url());
L('body text head: ' + (await page.locator('main').innerText()).slice(0, 600).replace(/\n/g, ' | '));
await page.screenshot({ path: '/tmp/c-p03-r11-w1-users.png' });
const stamp = Date.now().toString(36);
await page.keyboard.press('Alt+n'); await page.waitForTimeout(800);
L('after Alt+N focus: ' + await focused(page));
await page.keyboard.type(`clerk.${stamp}@alnoor.example`);
await page.keyboard.press('Alt+o'); await page.waitForTimeout(300);
L('after Alt+O focus: ' + await focused(page));
await page.keyboard.type('read'); await page.keyboard.press('Enter'); await page.waitForTimeout(300);
L('checked roles: ' + JSON.stringify(await page.locator('aside .id-roles input[type=checkbox]:checked').evaluateAll((els) => els.map((e) => e.closest('label')?.innerText))));
await page.screenshot({ path: '/tmp/c-p03-r11-w1-new.png' });
await page.keyboard.press('Control+Enter'); await page.waitForTimeout(1500);
L('after save aside: ' + (await page.locator('aside').first().innerText()).slice(0, 700).replace(/\n/g, ' | '));
await page.screenshot({ path: '/tmp/c-p03-r11-w1-saved.png' });
L('errors: ' + JSON.stringify(errors));
import fs from 'node:fs'; fs.writeFileSync(EV + '/walks/w1.txt', log.join('\n'));
await browser.close();

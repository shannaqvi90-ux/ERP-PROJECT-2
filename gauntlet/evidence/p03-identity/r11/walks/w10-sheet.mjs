import { open, signIn, focused, EV, BASE } from './h.mjs';
import fs from 'node:fs';
const log = []; const L = (s) => { log.push(s); console.log(s); };
const { browser, page } = await open({ width: 1600 });
await signIn(page, 'admin@alnoor.example');
await page.keyboard.press('g'); await page.keyboard.press('u'); await page.waitForTimeout(2500);
await page.keyboard.press('Alt+n'); await page.waitForTimeout(800);
await page.locator('aside h2, aside header').first().click().catch(() => {});
L('focus before ?: ' + await focused(page));
await page.keyboard.press('Shift+Slash'); await page.waitForTimeout(600);
let sheet = await page.locator('[role=dialog]').first().innerText().catch(() => '');
L('sheet via ? has "Find a role" with Alt+O: ' + /Find a role/.test(sheet) + ' ' + sheet.split('\n').filter((l) => /Find a role|Alt/.test(l)).slice(0, 8).join(' / '));
await page.keyboard.press('Escape');
L('footer link: ' + await page.locator('footer').innerText().catch(() => ''));
await page.locator('footer button, footer a').filter({ hasText: 'Shortcuts' }).first().click().catch((e) => L('no footer button ' + e.message.slice(0, 60)));
await page.waitForTimeout(600);
sheet = await page.locator('[role=dialog]').first().innerText().catch(() => '');
L('sheet via footer: Find a role present ' + /Find a role/.test(sheet) + ' | ' + sheet.replace(/\n/g, ' / ').slice(0, 900));
await page.screenshot({ path: '/tmp/c-p03-r11-sheet.png' });
fs.writeFileSync(`${EV}/walks/w10-shortcut-sheet.txt`, log.join('\n'));
await browser.close();

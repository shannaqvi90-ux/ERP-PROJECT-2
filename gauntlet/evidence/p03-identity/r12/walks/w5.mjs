// Walk 5: per-company role, per-user language and default company, the effective-permission view; then the user signs in.
import { open, signIn, focused, EV, BASE, shot } from './h.mjs';
import fs from 'node:fs';
const log = []; const L = (s) => { log.push(s); console.log(s); };
const { email } = JSON.parse(fs.readFileSync('w1.out.json', 'utf8'));
let { browser, page, errors } = await open({ width: 1600 });
await signIn(page, 'admin@alnoor.example');
await page.keyboard.press('g'); await page.keyboard.press('u'); await page.waitForTimeout(2500);
await page.keyboard.type(email); await page.keyboard.press('Enter'); await page.waitForTimeout(1500);
const sel = page.locator('aside select[name=companyRoleRole]');
L('company-role select value before choosing: "' + await sel.inputValue() + '" shown: ' + await sel.evaluate((s) => s.options[s.selectedIndex]?.text));
const add = page.locator('aside button').filter({ hasText: /^Add$/ });
L('Add disabled before a role is chosen: ' + await add.isDisabled());
await page.locator('aside select[name=language]').selectOption({ label: 'Arabic' });
await page.locator('aside select[name=companyRoleCompany]').selectOption({ label: 'ALN-DXB · Al Noor Trading LLC' });
await sel.selectOption({ label: 'Staff' });
await add.click(); await page.waitForTimeout(300);
const dc = page.locator('aside select[name=defaultCompany]');
L('default company options: ' + JSON.stringify(await dc.evaluate((s) => [...s.options].map((o) => o.text))));
await dc.selectOption({ label: 'ALN-DXB · Al Noor Trading LLC' });
await page.keyboard.press('Control+Enter'); await page.waitForTimeout(2000);
L('after save: ' + (await page.locator('aside').first().innerText()).slice(0, 250).replace(/\n/g, ' | '));
await page.locator('aside [role=tab]').filter({ hasText: 'What they can do' }).click(); await page.waitForTimeout(1200);
L('effective: ' + (await page.locator('aside [role=tabpanel]').innerText()).replace(/\n/g, ' | ').slice(0, 2500));
await shot(page, '08-what-they-can-do-company-role-en');
L('errors: ' + JSON.stringify(errors));
await browser.close();
({ browser, page, errors } = await open({ width: 1600 }));
await signIn(page, email, 'Clerk-Pass-2026!x');
L('clerk sees dir=' + await page.evaluate(() => document.documentElement.dir) + ' lang=' + await page.evaluate(() => document.documentElement.lang));
L('clerk header: ' + (await page.locator('header').first().innerText()).replace(/\n/g, ' | '));
await page.keyboard.press('g'); await page.keyboard.press('u'); await page.waitForTimeout(2500);
L('clerk users list: ' + (await page.locator('main').innerText()).slice(0, 250).replace(/\n/g, ' | '));
await shot(page, '09-restricted-user-arabic-list-ar');
L('errors: ' + JSON.stringify(errors));
fs.writeFileSync(`${EV}/walks/w5-company-role-language.txt`, log.join('\n'));
await browser.close();

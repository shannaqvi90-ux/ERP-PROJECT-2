import { open, signIn, focused, EV, BASE } from './h.mjs';
import fs from 'node:fs';
const log = []; const L = (s) => { log.push(s); console.log(s); };
const lang = process.argv[2] || 'en';
const { browser, page, errors } = await open({ width: 1600 });
await signIn(page, lang === 'en' ? 'admin@alnoor.example' : 'admin.ar@alnoor.example');
await page.goto(BASE + '/identity/roles'); await page.waitForTimeout(2000);
L('dir=' + await page.evaluate(() => document.documentElement.dir) + ' lang=' + await page.evaluate(() => document.documentElement.lang));
await page.keyboard.press('Alt+n'); await page.waitForTimeout(800);
L('new role focus: ' + await focused(page));
const stamp = Date.now().toString(36).slice(-5);
await page.keyboard.type(`Storekeeper ${stamp}`); await page.keyboard.press('Tab');
L('tab -> ' + await focused(page));
await page.keyboard.type(`أمين مخزن ${stamp}`); await page.keyboard.press('Tab');
L('tab -> ' + await focused(page));
await page.keyboard.type(lang === 'en' ? 'view' : 'عرض'); await page.waitForTimeout(500);
const btns = await page.locator('aside button:visible').evaluateAll((b) => b.map((x) => x.innerText.trim()).filter(Boolean));
L('buttons after search: ' + JSON.stringify(btns));
const selectAll = page.locator('aside button:visible').filter({ hasText: lang === 'en' ? 'Select all shown' : 'تحديد كل الظاهر' }).first();
L('select-all present: ' + await selectAll.count());
if (await selectAll.count()) await selectAll.click();
await page.waitForTimeout(300);
const ticked = await page.locator('aside input[type=checkbox]:checked').evaluateAll((els) => els.map((e) => e.getAttribute('aria-label')).filter(Boolean));
L(`ticked after select all on search: ${ticked.length} ${JSON.stringify(ticked)}`);
await page.screenshot({ path: `${EV}/${lang === 'en' ? '06' : '07'}-new-role-search-select-all-${lang}.jpg`, quality: 65, type: 'jpeg' });
await page.keyboard.press('Control+Enter'); await page.waitForTimeout(1500);
L('after save: ' + (await page.locator('aside').first().innerText()).slice(0, 200).replace(/\n/g, ' | '));
// copy role
const copyBtn = page.locator('aside button:visible').filter({ hasText: lang === 'en' ? 'Copy role' : /نسخ/ }).first();
L('copy button: ' + await copyBtn.count());
await copyBtn.click(); await page.waitForTimeout(800);
const names = await page.locator('aside input[type=text], aside input:not([type])').evaluateAll((els) => els.map((e) => e.value).filter(Boolean));
L('copy form names: ' + JSON.stringify(names));
await page.keyboard.press('Control+Enter'); await page.waitForTimeout(1500);
L('after copy save: ' + (await page.locator('aside').first().innerText()).slice(0, 200).replace(/\n/g, ' | '));
// delete the copy via palette
await page.keyboard.press('Control+k'); await page.waitForTimeout(300); await page.keyboard.type(lang === 'en' ? 'delete role' : 'حذف'); await page.waitForTimeout(500);
L('palette: ' + (await page.locator('[role=dialog]').first().innerText().catch(() => '')).slice(0, 200).replace(/\n/g, ' | '));
await page.keyboard.press('Enter'); await page.waitForTimeout(600);
L('after palette Enter focus: ' + await focused(page));
await page.keyboard.press('Enter'); await page.waitForTimeout(1500);
L('roles list now: ' + (await page.locator('main').innerText()).slice(0, 500).replace(/\n/g, ' | '));
L('errors: ' + JSON.stringify(errors));
fs.writeFileSync(`${EV}/walks/w4-roles-${lang}.txt`, log.join('\n'));
await browser.close();

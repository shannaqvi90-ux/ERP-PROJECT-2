// Edit an old contact's custom fields by keyboard, then read its History panel.
import { open, shot, text, focused } from './pw.mjs';
const email = process.argv[2] || 'admin@alnoor.example', tag = process.argv[3] || 'en', sfx = process.argv[4] || 'R4E', who = process.argv[5] || 'Gulf Glass';
const ar = tag === 'ar';
const { browser, page, errors } = await open(email);
const msgs = () => page.$$eval('[role=alert], [role=status], .field-error', els => els.map(e => e.textContent.trim()).filter(Boolean).slice(0, 6));
await page.keyboard.press('g'); await page.keyboard.press('o'); await page.waitForTimeout(2500);
await page.keyboard.press('/'); await page.keyboard.type(who); await page.waitForTimeout(2000);
await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); await page.waitForTimeout(3000);
console.log('opened', page.url());
const vals = () => page.$$eval('input[name^="customFields"], select[name^="customFields"]', els => els.map(e => [e.name, e.value]));
console.log('before', JSON.stringify(await vals()));
await page.keyboard.press('Control+s'); await page.waitForTimeout(2000); console.log('save unchanged old record:', await msgs());
await shot(page, `${tag}-old-record-saved-unchanged`);
const sel = `select[name="customFields.cfIncoterm${sfx}"]`, dt = `input[name="customFields.cfLicenceExpiry${sfx}"]`, num = `input[name="customFields.cfCreditCap${sfx}"]`;
await page.focus(sel); await page.keyboard.press('Home'); await page.keyboard.press('ArrowDown'); console.log('select', await focused(page));
await page.focus(dt); await page.keyboard.press('Control+a'); await page.keyboard.press('Backspace'); await page.keyboard.type(ar ? '٣١١٢٢٠٢٧' : '31122027'); console.log('date', await focused(page));
await page.focus(num); await page.keyboard.press('Control+a'); await page.keyboard.press('Backspace'); await page.keyboard.type(ar ? '٢٥٠٠٠٠٫٧٥' : '250000.75'); console.log('num', await focused(page));
await page.keyboard.press('Control+s'); await page.waitForTimeout(2000); console.log('save 1', await msgs());
await page.focus(sel); await page.keyboard.press('End'); console.log('select', await focused(page));
await page.focus(dt); await page.keyboard.press('Control+a'); await page.keyboard.press('Backspace'); await page.keyboard.type(ar ? '٠١٠٦٢٠٢٨' : '01062028');
await page.keyboard.press('Control+s'); await page.waitForTimeout(2000); console.log('save 2', await msgs());
console.log('after', JSON.stringify(await vals()));
await shot(page, `${tag}-contact-custom-values`);
await page.keyboard.press('Alt+y'); await page.waitForTimeout(3000);
await shot(page, `${tag}-history-panel`);
const t = await text(page);
console.log(t.split('\n').filter(l => /R4|EXW|FOB|CIF|فوب|سيف|تسليم|2027|2028|٢٠٢|250|٢٥٠|1,500|١٬٥٠٠/.test(l) && l.length < 160).slice(0, 30).join('\n'));
console.log('errors', errors); await browser.close();

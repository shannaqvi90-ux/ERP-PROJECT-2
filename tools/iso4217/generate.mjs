#!/usr/bin/env node
// Generates src/Kernel/Erp.Kernel/Money/Iso4217.g.cs from ISO 4217 List One (current currencies and
// funds) as published by the standard's maintenance agency, SIX Group on behalf of ISO:
//   https://www.six-group.com/en/products-services/financial-information/data-standards.html
//   https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml
//
//   node tools/iso4217/generate.mjs [list-one.xml]   (downloads the list when no file is given)
//
// Every alphabetic code with numeric minor units is kept once (several countries share one code);
// entries whose minor units are "N.A." (precious metals, special drawing rights, test and "no
// currency" codes) are left out: they are not currencies a company invoices or keeps accounts in.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const url = 'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
const xml = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(url)).text();
const published = /<ISO_4217 Pblshd="([0-9-]+)"/.exec(xml)?.[1];
if (!published) throw new Error('not ISO 4217 List One: no Pblshd attribute');
const entries = new Map();
for (const [, entry] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const field = (name) => new RegExp(`<${name}[^>]*>([^<]*)</${name}>`).exec(entry)?.[1]?.trim();
  const code = field('Ccy');
  const number = field('CcyNbr');
  const minor = field('CcyMnrUnts');
  if (!code || !/^[A-Z]{3}$/.test(code) || !minor || !/^\d$/.test(minor)) continue;
  if (!/^\d{3}$/.test(number ?? '')) throw new Error(`${code}: numeric code '${number}'`);
  const known = entries.get(code);
  if (known && (known.number !== number || known.minor !== Number(minor))) throw new Error(`${code}: conflicting entries`);
  entries.set(code, { number, minor: Number(minor) });
}
if (entries.size < 150) throw new Error(`only ${entries.size} currencies: not the full list`);
const lines = [...entries.keys()].sort().map((code) => {
  const { number, minor } = entries.get(code);
  return `        ["${code}"] = new(${Number(number)}, ${minor}),`;
});
const out = `// <auto-generated>
// Generated by tools/iso4217/generate.mjs from ISO 4217 List One published ${published} by the
// maintenance agency (SIX Group): ${url}
// Do not edit by hand: run the generator on a newer list.
// </auto-generated>
using System.Collections.Frozen;

namespace Erp.Kernel.Money;

/// <summary>ISO 4217 List One (published ${published}): every current currency and fund code with
/// its numeric code and minor units. Codes without minor units (metals, SDR, test codes) are left out.</summary>
public static class Iso4217
{
    /// <summary>The date of the list this table was generated from.</summary>
    public const string Published = "${published}";

    /// <summary>The list's numeric code and minor-unit digits of one currency.</summary>
    public readonly record struct Entry(int Number, int MinorUnits);

    public static readonly FrozenDictionary<string, Entry> Currencies = new Dictionary<string, Entry>(StringComparer.Ordinal)
    {
${lines.join('\n')}
    }.ToFrozenDictionary(StringComparer.Ordinal);
}
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'Kernel', 'Erp.Kernel', 'Money', 'Iso4217.g.cs');
writeFileSync(target, out);
console.log(`${entries.size} currencies from the list published ${published} -> ${target}`);
